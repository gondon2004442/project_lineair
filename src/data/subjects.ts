export const SUBJECTS_BY_ID = new Map(SUBJECTS.map((s) => [s.id, s]));

/** Стартовый субъект: тот, кто не замурован. */
export const SUBJECT_START = 'courier';

/** Кто замурован на этом уровне. Пусто — на этом уровне никого. */
export function walledAt(depth: number): SubjectSpec | undefined {
  return SUBJECTS.find((s) => s.walledAt === depth);
}

/** Описание субъекта. Неизвестный — стартовый: забег не должен падать. */
export function subjectAt(id: string): SubjectSpec {
  const spec = SUBJECTS_BY_ID.get(id) ?? SUBJECTS_BY_ID.get(SUBJECT_START);
  if (spec === undefined) throw new Error('Нет ни одного описания субъекта');
  return spec;
}
