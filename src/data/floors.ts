/**
 * ЭТАЖИ. Это ДАННЫЕ.
 *
 * Здание глубже, чем кажется, и каждый уровень — своё место, а не та же
 * арена с другим числом здоровья. Этаж описывается тем, из чего он
 * собирается: пулом планировок, пулом расписаний, начальником внизу.
 *
 * Искажение у каждого этажа ровно одно (раздел 6.3 документа), но на
 * этом шаге их нет ни у кого: сначала просто глубина. Поле объявлено
 * пустым, чтобы искажения легли в готовое место, а не переписывали
 * интерфейс.
 */
export interface FloorSpec {
  /** −1, −2, ... Чем глубже, тем меньше число. */
  depth: number;
  /** Как уровень подписан на табло лифта. */
  code: string;
  title: string;
  /** Планировки, из которых собирается этаж. Пусто — все подряд. */
  templates: string[];
  /**
   * Насколько этаж злее первого. Множитель к числу ставок: генератор
   * читает его вместо TUNING.floor.staffScale.
   */
  staffScale: number;
  /** Ключ искажения. Пусто — этаж честный. */
  distortion: string;
  /**
   * Расписание приёмной: кто сидит в конце этажа. Пусто — заведующий,
   * как на первом уровне.
   */
  headStaffing: string;
  /**
   * Должность, которая держит печать этого уровня. Пока она жива, лифт
   * вниз не подпишут.
   */
  sealHolder: string;
  /**
   * Стен нет — есть края. Плиты парят в пустоте, и за край можно уйти:
   * не в смерть, а в падение с возвратом. Признак отдельный от
   * искажения: искажение снимается приёмкой, а пустота никуда не
   * девается — здание здесь просто так устроено.
   */
  voidEdges?: boolean;
  /**
   * Планировка приёмной. Пусто — кабинет, как на первом уровне. В
   * бойлерной кабинета быть не может: отделки туда не доводили, и
   * начальник сидит в зале.
   */
  endTemplate?: string;
  /**
   * Уровень кончается не лифтом и не зачисткой, а решением: что сделать
   * с делом. Пока оно не принято, забег не кончается.
   */
  verdict?: boolean;
}

