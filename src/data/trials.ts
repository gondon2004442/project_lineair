/**
 * АТТЕСТАЦИЯ. Это ДАННЫЕ.
 *
 * Натурная часть устроена не как этаж из помещений, а как серия
 * испытаний между участками боя. Это не обучение: это проверка
 * соответствия перед выдачей следующего уровня допуска. Прошёл —
 * полномочия расширены, и расширены они навсегда для этого забега.
 *
 * Три испытания, по одному на каждое, чем натурная часть и занята:
 * плиты, которые уходят из-под ног; мишени, которые двигает Комиссия;
 * вес, который надо удержать, пока пол перестраивается.
 */
export interface Trial {
  id: string;
  code: string;
  title: string;
  /** Что надо сделать. Строки выводятся как есть. */
  report: string[];
  /** Ключ задачи: cross | targets | hold. */
  goal: string;
  /** Сколько требуется: секунд удержания, мишеней, перестроек. */
  need: number;
  /** Что выдают за прохождение: ключ полномочия. */
  grant: string;
  /** Как полномочие называется в деле. */
  grantTitle: string;
}

