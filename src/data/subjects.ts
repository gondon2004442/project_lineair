/**
 * СУБЪЕКТЫ. Это ДАННЫЕ.
 *
 * Субъект — не класс и не набор перков. Это тот, кого контора оформила:
 * у него своё свойство, своя сильная сторона и своя цена. Свойство
 * входит в `Directive.requiresTrait`, поэтому один и тот же набор
 * приложений у Электрика и у Картографа собирается в РАЗНЫЕ
 * распоряжения. В этом и смысл: субъект меняет не числа, а то, что
 * контора готова выпустить.
 *
 * Открываются они не «за достижение», а потому что кто-то остался
 * вместо них. Замурованный сотрудник лежит на своём уровне, и пока его
 * не освободили, играть им нельзя — его просто нет в штате.
 */
import type { ItemMod } from './items';

export interface SubjectSpec {
  id: string;
  /** Свойство: его читают распоряжения и системы. */
  trait: string;
  /** Номер наряда. По нему субъект и опознаётся. */
  code: string;
  title: string;
  /** Служебная справка: строки выводятся как есть. */
  report: string[];
  /** Правки, пока им играют: сильная сторона и цена одним списком. */
  mods: ItemMod[];
  /**
   * Сколько форм оружия у него на руках в начале забега. Это и есть
   * цена Картографа: схему он видит, а колесо у него на одну позицию.
   */
  forms: number;
  /**
   * На каком уровне он замурован. 0 — он не замурован нигде: таким
   * играют с самого начала.
   */
  walledAt: number;
  /**
   * Что он отдаёт, если его освободить. Только сильная сторона и без
   * цены: он отдаёт своё, а не нанимается вместо субъекта.
   */
  gift: ItemMod[];
}

