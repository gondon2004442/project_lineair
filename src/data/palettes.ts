const FALLBACK = FLOOR_PALETTES[-1];

/** Палитра уровня. За пределами списка — первая: падать нельзя. */
export function floorPalette(depth: number): FloorPalette {
  const spec = FLOOR_PALETTES[depth] ?? FALLBACK;
  if (spec === undefined) throw new Error('Нет ни одной палитры этажа');
  return spec;
}
