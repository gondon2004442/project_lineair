/**
 * ПАЛИТРЫ ЭТАЖЕЙ. Это ДАННЫЕ.
 *
 * Пять наборов, снятых со страницы FLOORS один в один, без подгонки на
 * глаз. Правило у них одно и сквозное: СВЕТЛОТА ВЕДЁТ ВНИЗ. Холл почти
 * белый, бойлерная почти чёрная — и спуск чувствуется по одной только
 * светлоте, без единой надписи.
 *
 * Отсюда же следует, что в коде не может быть зашито «стена темнее
 * пола»: на первом уровне бетон СВЕТЛЕЕ пола, а в натурной части
 * пустота светлее геометрии. Любое такое допущение этот набор ломает, и
 * это ровно то, ради чего он сделан первым.
 *
 * Красный, жёлтый и шкала бетона на телах сюда не входят и не меняются
 * никогда: субъект, должности и служебная разметка принадлежат игре, а
 * не этажу.
 */
export interface FloorPalette {
  /** Бетон стен. */
  wall: number;
  /** Пол. */
  floor: number;
  /** Шов между плитками пола. */
  floorSeam: number;
  /** Мебель и перегородки: укрытия, которые можно двигать и ломать. */
  furniture: number;
  /** Тёплая деталь этажа: дорожка, орех, бумага, ржавчина, прожилка. */
  accent: number;
  /** Вторая деталь: колонна, латунь, отсвет, кромка. */
  detail: number;
  /** Провал: дверной зев и шахта. Не фон экрана — он чёрный всегда. */
  pit: number;
}

