/**
 * СТОЙКИ. Это ДАННЫЕ.
 *
 * Наш аналог алтарей: место, где забег можно поправить, заплатив тем,
 * чего жалко. Стойка одноразовая — это не магазин, а окошко, в которое
 * подают один раз.
 *
 * Третья стойка в DESIGN-02 названа «стойкой выдачи», но стол выдачи у
 * нас уже есть — тот, что с ячейками. Две «выдачи» в одном оверлее
 * читать невозможно, поэтому здесь она ПЕРЕАТТЕСТАЦИЯ: смысл тот же —
 * бросок, который либо поднимет выслугу, либо добавит взыскание.
 */
export type CounterKind = 'registry' | 'hr' | 'review';

export interface CounterSpec {
  kind: CounterKind;
  title: string;
  /** Что стойка предлагает: строка идёт в приглашение у стойки. */
  offer: string;
  /** Насечек на табличке: по ним стойки различаются в кадре. */
  marks: number;
}

